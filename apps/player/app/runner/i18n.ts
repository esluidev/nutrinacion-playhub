const TABLES: Record<string, Record<RunnerTextKey, string>> = { es: ES, en: EN }

export function useRunnerText(locale: () => string) {
  return (key: RunnerTextKey, vars?: Record<string, string | number>): string =>
    fill(TABLES[locale()]?.[key] ?? ES[key], vars)
}
