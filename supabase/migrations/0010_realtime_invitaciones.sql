-- 0010 — Realtime en `invitaciones` (y SOLO en invitaciones)
-- ─────────────────────────────────────────────────────────────────────────────
-- Caso de uso: te invitan mientras estás con la sesión abierta. Sin esto, el sobre del
-- header no se entera hasta que recargues o cambies de ruta.
--
-- Por qué solo esta tabla: Realtime respeta RLS, pero `talleres`, `educadores`, `grupos`,
-- `colaboradores` y compañía siguen en `authenticated using(true)` — cualquier autenticado
-- las lee entera. Publicarlas convertiría ese tradeoff pasivo en una TRANSMISIÓN activa:
-- un colaborador de otra organización recibiría en su navegador cada cambio de la
-- operación ajena, sin pedirlo. `invitaciones` es la única que hoy filtra de verdad
-- (0005 + 0006: superadmin, las dirigidas a MI correo, y las de las orgs que administro),
-- así que es la única donde publicar no ensancha nada.
--
-- Cuando el RLS de la operación se apriete por comunidad (0011), `talleres` y
-- `taller_asignaciones_educadores` pasan a ser candidatas legítimas para el planificador.
--
-- No se toca REPLICA IDENTITY: alcanza la de por defecto. Al cliente solo le interesa
-- "algo cambió" para volver a consultar, y los eventos que importan (INSERT de una
-- invitación nueva, UPDATE al revocarla o aceptarla) traen el registro nuevo, con el que
-- Realtime puede evaluar la política del suscriptor.

alter publication supabase_realtime add table invitaciones;
